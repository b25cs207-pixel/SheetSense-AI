import os
import json
from typing import Optional, Dict, Any, List
import requests
from backend.config import settings

class BaseAIProvider:
    def generate_text(self, system_prompt: str, user_prompt: str, temperature: float = 0.2) -> str:
        raise NotImplementedError

class GeminiProvider(BaseAIProvider):
    def __init__(self, api_key: Optional[str] = None, model: str = "gemini-2.5-flash"):
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.model = model

    def generate_text(self, system_prompt: str, user_prompt: str, temperature: float = 0.2) -> str:
        if not self.api_key:
            raise ValueError("GEMINI_API_KEY is not configured.")
            
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"
        payload = {
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": f"{system_prompt}\n\nTask:\n{user_prompt}"}]
                }
            ],
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": 1500
            }
        }
        resp = requests.post(url, json=payload, timeout=20)
        resp.raise_for_status()
        data = resp.json()
        candidates = data.get("candidates", [])
        if candidates and "content" in candidates[0]:
            parts = candidates[0]["content"].get("parts", [])
            if parts:
                return parts[0].get("text", "")
        return "No response generated by model."

class OpenAIProvider(BaseAIProvider):
    def __init__(self, api_key: Optional[str] = None, model: str = "gpt-4o-mini"):
        self.api_key = api_key or settings.OPENAI_API_KEY
        self.model = model

    def generate_text(self, system_prompt: str, user_prompt: str, temperature: float = 0.2) -> str:
        if not self.api_key:
            raise ValueError("OPENAI_API_KEY is not configured.")

        url = "https://api.openai.com/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json"
        }
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "temperature": temperature,
            "max_tokens": 1500
        }
        resp = requests.post(url, headers=headers, json=payload, timeout=20)
        resp.raise_for_status()
        data = resp.json()
        return data["choices"][0]["message"]["content"]

class FallbackProvider(BaseAIProvider):
    """High-fidelity deterministic rule-based generator that guarantees 100% data grounding."""
    def generate_text(self, system_prompt: str, user_prompt: str, temperature: float = 0.2) -> str:
        return "Deterministic rule-based analysis active. All findings are derived directly from mathematical verification."

def get_ai_provider(provider_type: Optional[str] = None, api_key: Optional[str] = None) -> BaseAIProvider:
    p_type = (provider_type or settings.AI_PROVIDER).lower()
    
    if p_type == "gemini" and (api_key or settings.GEMINI_API_KEY):
        return GeminiProvider(api_key=api_key)
    elif p_type == "openai" and (api_key or settings.OPENAI_API_KEY):
        return OpenAIProvider(api_key=api_key)
    else:
        return FallbackProvider()
